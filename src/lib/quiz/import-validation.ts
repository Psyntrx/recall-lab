import type { AnswerKey, Question, QuizFile } from "./import";

export type ImportPreview = {
  title: string;
  summary?: string;
  questionCount: number;
  topics: string[];
  difficulties: { easy: number; medium: number; hard: number; unclassified: number };
  sampleQuestions: Array<{
    id: string;
    question: string;
    options: Record<AnswerKey, string>;
    correct_answer: AnswerKey;
    topic_reference: string;
    explanation: string;
    source_reference?: string | null;
  }>;
};

export type ImportValidationResult = {
  success: boolean;
  quiz?: QuizFile;
  preview?: ImportPreview;
  errors: string[];
  warnings: string[];
};

/**
 * Strips Markdown code block delimiters (```json ... ``` or ``` ... ```)
 * and trims surrounding whitespace.
 */
export function cleanRawJsonText(raw: string): string {
  let cleaned = raw.trim();
  // Strip Markdown code block if present
  if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/i, "").trim();
  }
  return cleaned;
}

/**
 * Validates a candidate JSON payload generated by an external AI against Recall Lab's schemas.
 * Returns understandable validation errors with exact question numbers, or a structured preview on success.
 */
export function validateExternalAiJson(input: string | unknown): ImportValidationResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  let candidate: Record<string, unknown>;

  if (typeof input === "string") {
    const cleaned = cleanRawJsonText(input);
    if (!cleaned) {
      return {
        success: false,
        errors: ["Please paste or upload JSON content."],
        warnings: [],
      };
    }
    try {
      candidate = JSON.parse(cleaned);
    } catch (parseErr) {
      return {
        success: false,
        errors: [
          `Invalid JSON syntax: ${parseErr instanceof Error ? parseErr.message : "Could not parse JSON"}. Ensure quotes, commas, and brackets are balanced.`,
        ],
        warnings: [],
      };
    }
  } else if (input && typeof input === "object") {
    candidate = input as Record<string, unknown>;
  } else {
    return {
      success: false,
      errors: ["The input must be a valid JSON object with a 'questions' array."],
      warnings: [],
    };
  }

  if (!candidate || typeof candidate !== "object" || Array.isArray(candidate)) {
    return {
      success: false,
      errors: ["Root JSON value must be an object containing a 'questions' list."],
      warnings: [],
    };
  }

  // Handle case where AI wrapped output in { data: { questions: [...] } } or { quiz: { questions: [...] } }
  if (!Array.isArray(candidate.questions)) {
    if (candidate.quiz && typeof candidate.quiz === "object" && Array.isArray((candidate.quiz as Record<string, unknown>).questions)) {
      candidate = candidate.quiz as Record<string, unknown>;
      warnings.push("Extracted quiz data from nested 'quiz' wrapper.");
    } else if (candidate.data && typeof candidate.data === "object" && Array.isArray((candidate.data as Record<string, unknown>).questions)) {
      candidate = candidate.data as Record<string, unknown>;
      warnings.push("Extracted quiz data from nested 'data' wrapper.");
    } else {
      errors.push("Missing required 'questions' array. Expected format: { \"title\": \"...\", \"questions\": [...] }.");
      return { success: false, errors, warnings };
    }
  }

  const rawQuestions = candidate.questions as unknown[];
  if (rawQuestions.length === 0) {
    errors.push("The 'questions' array is empty. At least 1 question is required.");
    return { success: false, errors, warnings };
  }

  if (rawQuestions.length > 30) {
    errors.push(`A quiz can contain at most 30 questions. Found ${rawQuestions.length} questions.`);
  }

  const validQuestions: Question[] = [];
  const seenIds = new Set<string>();
  const seenStems = new Set<string>();

  for (let i = 0; i < rawQuestions.length; i++) {
    const rawQ = rawQuestions[i];
    const qNum = i + 1;
    const prefix = `Question ${qNum}`;

    if (!rawQ || typeof rawQ !== "object" || Array.isArray(rawQ)) {
      errors.push(`${prefix} is not a valid object.`);
      continue;
    }

    const q = rawQ as Record<string, unknown>;

    // Validate ID
    let id = typeof q.id === "string" ? q.id.trim() : "";
    if (!id) {
      id = `q${qNum}`;
      warnings.push(`${prefix}: Missing 'id'; assigned '${id}'.`);
    } else if (seenIds.has(id)) {
      errors.push(`${prefix}: Duplicate question id '${id}'.`);
    }
    seenIds.add(id);

    // Validate Question Stem
    const stem = typeof q.question === "string" ? q.question.trim() : "";
    if (!stem) {
      errors.push(`${prefix}: Missing or empty 'question' text.`);
    } else if (stem.length < 5) {
      errors.push(`${prefix}: Question text is too short (minimum 5 characters).`);
    } else {
      const lowerStem = stem.toLowerCase();
      if (seenStems.has(lowerStem)) {
        errors.push(`${prefix}: Duplicate question stem. Questions must be distinct.`);
      }
      seenStems.add(lowerStem);
    }

    // Validate Options
    const optionsObj = q.options as Record<string, unknown> | undefined;
    if (!optionsObj || typeof optionsObj !== "object" || Array.isArray(optionsObj)) {
      errors.push(`${prefix}: Missing 'options' object. Must have exactly keys 'A', 'B', 'C', 'D'.`);
    } else {
      const keys = ["A", "B", "C", "D"] as const;
      const missingKeys = keys.filter((k) => typeof optionsObj[k] !== "string" || !(optionsObj[k] as string).trim());
      if (missingKeys.length > 0) {
        errors.push(`${prefix}: Missing or empty option(s): ${missingKeys.join(", ")}.`);
      } else {
        const optionValues = keys.map((k) => (optionsObj[k] as string).trim());
        const uniqueValues = new Set(optionValues.map((v) => v.toLowerCase()));
        if (uniqueValues.size !== 4) {
          errors.push(`${prefix}: All four options (A, B, C, D) must be distinct.`);
        }
      }
    }

    // Validate Correct Answer
    const validAnswers: AnswerKey[] = ["A", "B", "C", "D"];
    const ca = typeof q.correct_answer === "string" ? q.correct_answer.trim().toUpperCase() : "";
    if (!validAnswers.includes(ca as AnswerKey)) {
      errors.push(`${prefix}: 'correct_answer' must be one of 'A', 'B', 'C', or 'D'. Received: '${q.correct_answer}'.`);
    }

    // Validate Topic Reference
    const topic = typeof q.topic_reference === "string" ? q.topic_reference.trim() : "";
    if (!topic) {
      errors.push(`${prefix}: Missing required 'topic_reference'.`);
    }

    // Validate Explanation
    const explanation = typeof q.explanation === "string" ? q.explanation.trim() : "";
    if (!explanation) {
      errors.push(`${prefix}: Missing required 'explanation'.`);
    }

    // Validate Source Reference
    let sourceRef: string | null = null;
    if (q.source_reference !== undefined && q.source_reference !== null) {
      if (typeof q.source_reference === "string") {
        sourceRef = q.source_reference.trim() || null;
      } else {
        errors.push(`${prefix}: 'source_reference' must be a string or null.`);
      }
    }

    if (errors.length === 0 || errors.every((e) => !e.startsWith(prefix))) {
      const formattedQ: Question = {
        id,
        question: stem,
        options: {
          A: String((optionsObj as any)?.A ?? "").trim(),
          B: String((optionsObj as any)?.B ?? "").trim(),
          C: String((optionsObj as any)?.C ?? "").trim(),
          D: String((optionsObj as any)?.D ?? "").trim(),
        },
        correct_answer: ca as AnswerKey,
        topic_reference: topic,
        explanation,
        source_reference: sourceRef,
      };

      if (typeof q.chapter === "string" && q.chapter.trim()) {
        formattedQ.chapter = q.chapter.trim();
      }
      if (q.difficulty === "easy" || q.difficulty === "medium" || q.difficulty === "hard") {
        formattedQ.difficulty = q.difficulty;
      }
      if (q.question_source === "extracted" || q.question_source === "generated" || q.question_source === "adapted") {
        formattedQ.question_source = q.question_source;
      }

      validQuestions.push(formattedQ);
    }
  }

  if (errors.length > 0) {
    return {
      success: false,
      errors,
      warnings,
    };
  }

  const rawTitle = typeof candidate.title === "string" ? candidate.title.trim() : "";
  const title = rawTitle || "Imported Study Quiz";

  const quiz: QuizFile = {
    title,
    questions: validQuestions,
  };

  // Build preview metadata
  const topicsSet = new Set<string>();
  const difficulties = { easy: 0, medium: 0, hard: 0, unclassified: 0 };

  for (const q of validQuestions) {
    if (q.topic_reference) topicsSet.add(q.topic_reference);
    if (q.difficulty === "easy") difficulties.easy++;
    else if (q.difficulty === "medium") difficulties.medium++;
    else if (q.difficulty === "hard") difficulties.hard++;
    else difficulties.unclassified++;
  }

  const sampleQuestions = validQuestions.slice(0, 3).map((q) => ({
    id: q.id,
    question: q.question,
    options: q.options,
    correct_answer: q.correct_answer,
    topic_reference: q.topic_reference,
    explanation: q.explanation,
    source_reference: q.source_reference,
  }));

  const preview: ImportPreview = {
    title,
    summary: typeof candidate.summary === "string" ? candidate.summary.trim() : undefined,
    questionCount: validQuestions.length,
    topics: Array.from(topicsSet),
    difficulties,
    sampleQuestions,
  };

  return {
    success: true,
    quiz,
    preview,
    errors: [],
    warnings,
  };
}
